import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
// Install jsdom for DOM tests only. No browser or external service is launched.
const require = createRequire(import.meta.url);
const { JSDOM } = require(process.env.LATENT_JSDOM_PATH || 'jsdom');
const root = new URL('../', import.meta.url);

test('the actual page supports replay comparison, filtering, local input, safe rendering, and exports', async () => {
  const html = await readFile(new URL('signal.html', root), 'utf8');
  const dom = new JSDOM(html, {url: 'https://aryanma.github.io/latent/signal.html?task=1'});
  globalThis.document = dom.window.document;
  globalThis.location = dom.window.location;
  const requests = [];
  globalThis.fetch = async path => {
    requests.push(path);
    return {ok: true, json: async () => JSON.parse(await readFile(new URL(path, root), 'utf8'))};
  };
  const downloads = [], blobs = [];
  URL.createObjectURL = blob => {blobs.push(blob); return 'blob:local-test';};
  URL.revokeObjectURL = () => {};
  dom.window.HTMLAnchorElement.prototype.click = function () {downloads.push(this.download);};
  await import('./app.mjs');
  const $ = id => document.getElementById(id);
  for (let i = 0; i < 100 && $('workspace').hidden; i++) await new Promise(r => setTimeout(r, 5));
  assert.equal($('workspace').hidden, false, $('load-status').textContent);
  assert.equal($('task-select').options.length, 50);
  assert.equal($('task-select').value, '1');
  assert.match($('replay-content').textContent, /I cannot approve this cancellation/);
  assert.match($('replay-content').textContent, /I approve this cancellation/);
  assert.match($('replay-content').textContent, /Same scalar reward \(1\)/);
  const event = type => new dom.window.Event(type, {bubbles: true});
  $('task-select').value = '19'; $('task-select').dispatchEvent(event('change'));
  assert.match($('replay-content').textContent, /Reward changed from 1 to 0/);
  $('probe-b').value = 'reference_plus_harmless_read'; $('probe-b').dispatchEvent(event('change'));
  assert.match($('replay-content').textContent, /Same scalar reward \(1\)/);
  $('task-select').value = '3'; $('task-select').dispatchEvent(event('change'));
  assert.match($('replay-content').textContent, /Not executed/);
  $('task-filter').value = 'empty_communication'; $('task-filter').dispatchEvent(event('change'));
  assert.equal($('task-select').options.length, 44);
  $('task-search').value = 'never-a-matching-description'; $('task-search').dispatchEvent(event('input'));
  assert.equal($('no-matches').hidden, false);
  assert.equal($('task-detail').childElementCount, 0);
  $('json-input').value = '{not valid'; $('inspect-paste').click();
  assert.equal($('input-error').hidden, false);
  const imported = [{id: '<script>alert(1)</script>', description:{purpose: '<img src=x onerror=alert(1)>'}, evaluation_criteria:{reward_basis:['COMMUNICATE'],communicate_info:['A real fact'],nl_assertions:['A written obligation']}}];
  $('json-input').value = JSON.stringify(imported); $('inspect-paste').click();
  assert.equal($('input-error').hidden, true);
  assert.equal($('task-select').options.length, 1);
  assert.match($('task-detail').textContent, /<img src=x onerror=alert\(1\)>/);
  assert.equal($('task-detail').querySelectorAll('img,script').length, 0);
  assert.match($('replay-content').textContent, /Unmeasured/);
  $('export-json').click(); $('export-csv').click();
  assert.deepEqual(downloads, ['latent-signal-audit.json','latent-signal-audit.csv']);
  const exported = JSON.parse(await blobs[0].text());
  assert.equal(exported.evidence, 'static-contract-audit');
  assert.equal(exported.summary.empty_communication, 0);
  assert.equal(exported.summary.ungated_nl, 1);
  // Exercise the asynchronous file input, without sending file bytes to fetch.
  Object.defineProperty($('task-file'), 'files', {configurable: true, value: [{name:'local.json',size:100,text:async ()=>'[{"id":"file-task","evaluation_criteria":{"reward_basis":[]}}]'}]});
  $('task-file').dispatchEvent(event('change'));
  await new Promise(r => setTimeout(r, 0));
  assert.match($('source-name').textContent, /local.json/);
  assert.equal($('task-select').value, 'file-task');
  assert.match($('task-detail').textContent, /No reward components/);
  assert.deepEqual(requests, ['./data/signal/airline-tasks.json','./data/signal/replays.json']);
  $('load-example').click();
  assert.equal($('task-select').options.length, 50);
  assert.equal($('task-select').value, '1');
  dom.window.close();
});
